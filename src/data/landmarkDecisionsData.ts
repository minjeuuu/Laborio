export function getLandmarkDecisionByTopicId(topicId: string): LandmarkDecision | undefined {
  return LANDMARK_DECISIONS_DATA.find((d) => d.topicId === topicId);
}

export function getLandmarkDecisionsByWorldId(worldId: string): LandmarkDecision[] {
  return LANDMARK_DECISIONS_DATA.filter((d) => d.worldId === worldId);
}

export function searchLandmarkDecisions(query: string): LandmarkDecision[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return [...LANDMARK_DECISIONS_DATA];
  return LANDMARK_DECISIONS_DATA.filter(
    (d) =>
      d.caseTitle.toLowerCase().includes(clean) ||
      d.grNumber.toLowerCase().includes(clean) ||
      d.doctrinalHolding.toLowerCase().includes(clean) ||
      d.statutoryBasis.toLowerCase().includes(clean) ||
      d.topicTitle.toLowerCase().includes(clean)
  );
}
